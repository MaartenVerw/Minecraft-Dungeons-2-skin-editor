    public static int Width(string text, int scale) => text.Length == 0 ? 0 : (text.Length * Advance - 1) * scale;
    public static int Height(int scale) => GlyphH * scale;

    public static void Draw(RgbaImage img, string text, int x, int y, int scale, uint colour, uint? shadow = null)
    {
        if (shadow is uint s) Draw(img, text, x + scale, y + scale, scale, s);
        foreach (char raw in text)
        {
            char c = raw == 'x' ? 'x' : char.ToUpperInvariant(raw);
            if (Glyphs.TryGetValue(c, out var g))
                for (int row = 0; row < GlyphH; row++)
                    for (int col = 0; col < GlyphW; col++)
                        if (g[row][col] == '#')
                            img.FillRect(x + col * scale, y + row * scale, scale, scale, colour);
            x += Advance * scale;
        }
    }
}
